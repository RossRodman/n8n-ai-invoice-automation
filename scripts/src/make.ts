import { mkdtemp, mkdir, rm, stat, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { findChrome, printToPdf, screenshot } from "./chrome.ts";
import { INVOICES } from "./data.ts";
import { type ExpectedFile, toExpected } from "./expected.ts";
import { EXPECTED_FILE, SAMPLES_DIR } from "./paths.ts";
import { makeScan } from "./scan.ts";
import { renderDe } from "./templates/de.ts";
import { renderUa } from "./templates/ua.ts";

const chrome = findChrome();
const workdir = await mkdtemp(join(tmpdir(), "invoice-samples-"));
await mkdir(SAMPLES_DIR, { recursive: true });

try {
  for (const inv of INVOICES) {
    const stem = inv.file.replace(/\.pdf$/, "");
    const page = join(workdir, `${stem}.html`);
    const out = join(SAMPLES_DIR, inv.file);
    await writeFile(page, inv.layout === "ua" ? renderUa(inv) : renderDe(inv));

    if (inv.scanned) {
      const shot = join(workdir, `${stem}.png`);
      screenshot(chrome, page, shot);

      await makeScan(shot, out, `Рахунок № ${inv.number}`);
    } else {
      printToPdf(chrome, page, out);
    }
    console.log(
      `  samples/invoices/${inv.file}  (${Math.round((await stat(out)).size / 1024)} KB)`,
    );
  }
} finally {
  await rm(workdir, { recursive: true, force: true });
}

const expected: ExpectedFile = {
  description:
    "What the workflow should extract from each test invoice, and where it should send it. Generated by scripts/src/make.ts.",
  invoices: INVOICES.map(toExpected),
};

await writeFile(EXPECTED_FILE, `${JSON.stringify(expected, null, 2)}\n`);
console.log("  samples/invoices/expected.json");
